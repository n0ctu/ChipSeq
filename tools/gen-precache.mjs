// Works out what the app actually loads, and writes it into sw.js.
//
//   node tools/gen-precache.mjs            rewrite the generated block
//   node tools/gen-precache.mjs --check    fail if it is stale (what CI runs)
//
// The list is DERIVED rather than maintained. It starts at index.html and the
// manifest and follows what is really there: stylesheets, the module entry
// point, the icon sprite, every static and dynamic import reachable from
// js/main.js, the manifest's icons, and the demo songs named by
// demos/index.json.
//
// The alternative is a hand-written list, and tests/check.mjs is the argument
// against it: it lists modules by hand and has silently missed
// core/badge-tune.js and net/badge-upload.js since they were added. A list that
// drifts there costs a gap in coverage. A list that drifts HERE costs a module
// that is missing only when the user is offline.
//
// An import this cannot resolve is an error rather than a skip: a file left out
// of the precache would work perfectly until the moment it mattered.

import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { posix } from 'node:path';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const SW = 'sw.js';

const BEGIN = '// ---- GENERATED by tools/gen-precache.mjs - do not edit by hand ----';
const END = '// ---- END GENERATED ----';

const read = (path) => readFileSync(ROOT + path, 'utf8');
const bytes = (path) => readFileSync(ROOT + path);

// ---- walking ----

// Same-origin, relative, no fragment. External URLs and bare specifiers are not
// ours to cache.
function local(ref, from) {
  if (!ref || /^[a-z]+:/i.test(ref) || ref.startsWith('//') || ref.startsWith('#')) return null;
  const clean = ref.split('#')[0].split('?')[0];
  if (!clean) return null;
  return posix.normalize(posix.join(posix.dirname(from), clean));
}

function refsFromHtml(html, from) {
  const out = [];
  for (const m of html.matchAll(/\b(?:href|src)\s*=\s*["']([^"']+)["']/g)) {
    const path = local(m[1], from);
    if (path) out.push(path);
  }
  return out;
}

function refsFromJs(src, from) {
  const out = [];
  // `from '…'`, `import '…'`, and dynamic import('…') including the template
  // literals the tool cards use.
  const patterns = [
    /\bfrom\s*["']([^"']+)["']/g,
    /\bimport\s*["']([^"']+)["']/g,
    /\bimport\s*\(\s*["'`]([^"'`]+)["'`]\s*\)/g,
  ];
  for (const re of patterns) {
    for (const m of src.matchAll(re)) {
      const ref = m[1];
      // `./x.js?v=${APP_VERSION}` is fine - the query is stripped. A
      // substitution in the PATH would make the target unknowable, and
      // guessing is how a file goes missing offline.
      if (ref.split('?')[0].includes('${')) {
        throw new Error(`${from}: cannot resolve a computed import path: ${ref}`);
      }
      if (!ref.startsWith('.') && !ref.startsWith('/')) continue; // bare specifier
      const path = local(ref, from);
      if (path) out.push(path);
    }
  }
  return out;
}

// demos/index.json is data, not code, so it gets an expander rather than being
// discovered: js/main.js fetches the names out of it at boot.
function refsFromJson(text, from) {
  if (from !== 'demos/index.json') return [];
  return JSON.parse(text).map((file) => posix.join('demos', file));
}

function refsFromManifest(text) {
  const manifest = JSON.parse(text);
  return (manifest.icons || []).map((icon) => local(icon.src, 'manifest.webmanifest')).filter(Boolean);
}

const ROOTS = ['index.html', 'manifest.webmanifest', 'demos/index.json'];

export function walk() {
  const seen = new Set();
  const queue = [...ROOTS];
  while (queue.length) {
    const path = queue.shift();
    if (seen.has(path)) continue;
    seen.add(path);
    let refs = [];
    if (path.endsWith('.html')) refs = refsFromHtml(read(path), path);
    else if (path.endsWith('.js')) refs = refsFromJs(read(path), path);
    else if (path === 'manifest.webmanifest') refs = refsFromManifest(read(path));
    else if (path.endsWith('.json')) refs = refsFromJson(read(path), path);
    for (const ref of refs) if (!seen.has(ref)) queue.push(ref);
  }
  // sw.js caching itself would be circular: the browser fetches and updates it
  // outside the cache, which is the only reason an update can ever be noticed.
  seen.delete(SW);
  return [...seen].sort();
}

const hash = (path) => createHash('sha256').update(bytes(path)).digest('hex').slice(0, 12);

// ---- the generated block ----

export function buildBlock() {
  const version = read('js/core/version.js').match(/APP_VERSION\s*=\s*'([^']+)'/)[1];
  const lines = walk().map((path) => `  ['${path}', '${hash(path)}'],`);
  return [BEGIN, `const VERSION = '${version}';`, 'const ASSETS = [', ...lines, '];', END].join('\n');
}

export function currentBlock() {
  const src = read(SW);
  const from = src.indexOf(BEGIN);
  const to = src.indexOf(END);
  if (from < 0 || to < 0) throw new Error(`${SW}: generated block markers are missing`);
  return src.slice(from, to + END.length);
}

function apply() {
  const src = read(SW);
  const next = src.replace(currentBlock(), buildBlock());
  writeFileSync(ROOT + SW, next);
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const wanted = buildBlock();
  if (process.argv.includes('--check')) {
    if (currentBlock() === wanted) {
      console.log(`${SW} precache list is current (${walk().length} files)`);
    } else {
      console.error(`${SW} precache list is STALE - run: node tools/gen-precache.mjs`);
      process.exit(1);
    }
  } else {
    apply();
    const list = walk();
    const total = list.reduce((n, path) => n + bytes(path).length, 0);
    console.log(`${SW}: ${list.length} files, ${(total / 1024).toFixed(0)} KB`);
  }
}
